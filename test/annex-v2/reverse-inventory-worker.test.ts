import * as net from 'net';
import { describe, it } from 'vitest';
import { createInventoryPeer } from './reverse-inventory-peer';
import { rpcPeer } from './reverse-parity-fixture';

describe.runIf(process.env.CLUBHOUSE_ANNEX_INVENTORY_PEER === '1')('isolated full-server parity peer', () => {
  it('serves the parent over IPC until stopped', async () => {
    const peer = await createInventoryPeer('B');
    let stop!: () => void;
    const stopped = new Promise<void>((resolve) => { stop = resolve; });
    const socket = net.connect(process.env.CLUBHOUSE_ANNEX_INVENTORY_IPC!);
    await new Promise<void>((resolve, reject) => { socket.once('connect', resolve); socket.once('error', reject); });
    let closed = false;
    const rpc = rpcPeer(socket, async (method, params) => {
      switch (method) {
        case 'info': return peer.info;
        case 'configure': return peer.configure(params as Parameters<typeof peer.configure>[0]);
        case 'status': return peer.status();
        case 'revokeRemote': return peer.revokeRemote();
        case 'setRemotePending': return peer.setRemotePending(params as boolean);
        case 'acceptOnlyFeatures': return peer.acceptOnlyFeatures(params as string[] | null);
        case 'holdProviderSend': return peer.holdProviderSend();
        case 'releaseProviderSend': return peer.releaseProviderSend();
        case 'wire': return peer.wire(params as Parameters<typeof peer.wire>[0]);
        case 'cancellableRead': return peer.cancellableRead(params as Parameters<typeof peer.cancellableRead>[0]);
        case 'cancelRead': return peer.cancelRead();
        case 'probe': return peer.probe(params as Parameters<typeof peer.probe>[0]);
        case 'chat': return peer.chat(params as Parameters<typeof peer.chat>[0]);
        case 'chatOutcome': return peer.chatOutcome(params as Parameters<typeof peer.chatOutcome>[0]);
        case 'cancellableWrite': return peer.cancellableWrite(params as Parameters<typeof peer.cancellableWrite>[0]);
        case 'cancelWrite': return peer.cancelWrite();
        case 'page': return peer.page(params as Parameters<typeof peer.page>[0]);
        case 'chatSessions': return peer.chatSessions();
        case 'openRequests': return peer.openRequests();
        case 'requestsState': return peer.requestsState();
        case 'answerGrant': return peer.answerGrant(params as Parameters<typeof peer.answerGrant>[0]);
        case 'hook': return peer.hook();
        case 'theme': return peer.theme();
        case 'canvas': return peer.canvas();
        case 'send': return peer.send(params as Parameters<typeof peer.send>[0]);
        case 'emitPty': return peer.emitPty(params as string);
        case 'floodPty': return peer.floodPty(params as { chunks: number; bytes: number });
        case 'ptyState': return peer.ptyState(params as string);
        case 'clipboardReceipt': return peer.clipboardReceipt();
        case 'ptyBuffer': return peer.ptyBuffer(params as string);
        case 'agentCall': return peer.agentCall(params as Parameters<typeof peer.agentCall>[0]);
        case 'deliveredFile': return peer.deliveredFile(params as string);
        case 'connections': return peer.connections();
        case 'connectionTools': return peer.connectionTools(params as string[]);
        case 'projectLink': return peer.projectLink(params as boolean);
        case 'linkedState': return peer.linkedState();
        case 'projectPin': return peer.projectPin(params as boolean);
        case 'projectInactive': return peer.projectInactive(params as boolean);
        case 'createNetworkGroup': return peer.createNetworkGroup(params as Parameters<typeof peer.createNetworkGroup>[0]);
        case 'networkGroup': return peer.networkGroup(params as string);
        case 'networkPost': return peer.networkPost(params as Parameters<typeof peer.networkPost>[0]);
        case 'networkUpdate': return peer.networkUpdate(params as Parameters<typeof peer.networkUpdate>[0]);
        case 'networkRole': return peer.networkRole(params as Parameters<typeof peer.networkRole>[0]);
        case 'networkAgentWrite': return peer.networkAgentWrite(params as Parameters<typeof peer.networkAgentWrite>[0]);
        case 'networkRoster': return peer.networkRoster(params as string);
        case 'controllerGroup': return peer.controllerGroup(params as Parameters<typeof peer.controllerGroup>[0]);
        case 'prepareHandoffs': return peer.prepareHandoffs();
        case 'handoffOffer': return peer.handoffOffer();
        case 'handoffRecord': return peer.handoffRecord(params as string);
        case 'handoffAccept': return peer.handoffAccept(params as string);
        case 'handoffPull': return peer.handoffPull(params as string);
        case 'handoffCancel': return peer.handoffCancel(params as string);
        case 'prepareImages': return peer.prepareImages();
        case 'imageState': return peer.imageState();
        case 'evictImageConfig': return peer.evictImageConfig();
        case 'imageUpload': return peer.imageUpload(params as Parameters<typeof peer.imageUpload>[0]);
        case 'receivedImage': return peer.receivedImage();
        case 'prepareLifecycle': return peer.prepareLifecycle();
        case 'lifecycleState': return peer.lifecycleState(params as string);
        case 'deleteRemoteAgent': return peer.deleteRemoteAgent(params as string);
        case 'externalConfigEdit': return peer.externalConfigEdit();
        case 'initializeProject': return peer.initializeProject();
        case 'durable': return peer.durable(params as Parameters<typeof peer.durable>[0]);
        case 'durableState': return peer.durableState(params as Parameters<typeof peer.durableState>[0]);
        case 'seedLargeText': return peer.seedLargeText();
        case 'seedContent': return peer.seedContent(params as number);
        case 'largeText': return peer.largeText();
        case 'emit': return peer.emit(params as Parameters<typeof peer.emit>[0]);
        case 'driverState': return peer.driverState();
        case 'seedLargeDiff': return peer.seedLargeDiff();
        case 'gitDiff': return peer.gitDiff();
        case 'seedGitProject': return peer.seedGitProject();
        case 'gitOperation': return peer.gitOperation(params as Parameters<typeof peer.gitOperation>[0]);
        case 'editGit': return peer.editGit(params as string);
        case 'gitState': return peer.gitState();
        case 'advanceGitRemote': return peer.advanceGitRemote();
        case 'seedLargeBoard': return peer.seedLargeBoard();
        case 'bulletin': return peer.bulletin(params as Parameters<typeof peer.bulletin>[0]);
        case 'seedLargeTranscript': return peer.seedLargeTranscript();
        case 'nativeSessions': return peer.nativeSessions();
        case 'nativeSummary': return peer.nativeSummary();
        case 'transcript': return peer.transcript();
        case 'stop':
          await peer.close();
          closed = true;
          setImmediate(stop);
          return true;
        default: throw new Error(`Unknown inventory fixture method: ${method}`);
      }
    });
    try { await stopped; }
    finally { if (!closed) await peer.close(); rpc.close(); }
  }, 180_000);
});
