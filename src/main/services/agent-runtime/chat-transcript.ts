/**
 * Append-only chat transcript: one JSONL file per agent under
 * `<userData>/agent-logs/chat/`, holding every stamped ChatEvent across all of
 * the agent's chat sessions in order. This is what the chat view renders
 * (Clubhouse owns history; the CLI's native session is used only to resume).
 */

import * as fs from 'fs';
import * as fsp from 'fs/promises';
import * as path from 'path';
import { app } from 'electron';
import { isChatEvent, type ChatEvent } from '../../../shared/chat';

function transcriptDir(): string {
  return path.join(app.getPath('userData'), 'agent-logs', 'chat');
}

export function transcriptPath(agentId: string): string {
  // Agent ids are generated by Clubhouse, but never trust them as path segments.
  const safe = agentId.replace(/[^A-Za-z0-9._-]/g, '_');
  return path.join(transcriptDir(), `${safe}.jsonl`);
}

/** Serialized appends per agent so lines never interleave. */
const writeChains = new Map<string, Promise<void>>();
/** Files already checked this process for a crash-torn last line. */
const checkedForTornLine = new Set<string>();

/** True when the file exists, is non-empty and doesn't end with a newline. */
async function endsMidLine(file: string): Promise<boolean> {
  let handle: fsp.FileHandle | undefined;
  try {
    handle = await fsp.open(file, 'r');
    const { size } = await handle.stat();
    if (size === 0) return false;
    const buf = Buffer.alloc(1);
    await handle.read(buf, 0, 1, size - 1);
    return buf[0] !== 0x0a;
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') return false;
    throw err;
  } finally {
    await handle?.close();
  }
}

export function appendChatEvent(event: ChatEvent): Promise<void> {
  const file = transcriptPath(event.agentId);
  const line = JSON.stringify(event) + '\n';
  const prev = writeChains.get(file) ?? Promise.resolve();
  const next = prev
    .catch((): void => undefined)
    .then(async () => {
      await fsp.mkdir(path.dirname(file), { recursive: true });
      // After a crash the last line can be torn. Start on a fresh line so the
      // next event isn't glued onto it and lost with it.
      let prefix = '';
      if (!checkedForTornLine.has(file)) {
        checkedForTornLine.add(file);
        if (await endsMidLine(file)) prefix = '\n';
      }
      await fsp.appendFile(file, prefix + line, 'utf-8');
    });
  writeChains.set(file, next);
  return next;
}

/** Resolves when all pending appends for this agent are on disk. */
export async function flushTranscript(agentId: string): Promise<void> {
  await (writeChains.get(transcriptPath(agentId)) ?? Promise.resolve()).catch((): void => undefined);
}

/** Resolves when every agent's pending appends are on disk. For app shutdown. */
export async function flushAllTranscripts(): Promise<void> {
  await Promise.all([...writeChains.values()].map((chain) => chain.catch((): void => undefined)));
}

export interface ReadTranscriptOptions {
  /** Only events from this chat session. */
  sessionId?: string;
  /** Only events with seq greater than this (requires sessionId). */
  afterSeq?: number;
  /** Only the last N events after filtering. */
  tail?: number;
}

/** Bytes read per step when reading a tail from the end of the file. */
const TAIL_CHUNK_BYTES = 64 * 1024;

/**
 * Read only enough of the end of the file for `tail` lines, so frequent
 * pollers (MCP read_output) don't parse the whole transcript each time.
 */
async function readTailText(file: string, tail: number): Promise<string> {
  const handle = await fsp.open(file, 'r');
  try {
    const { size } = await handle.stat();
    let position = size;
    let text = '';
    let newlines = 0;
    while (position > 0 && newlines <= tail) {
      const length = Math.min(TAIL_CHUNK_BYTES, position);
      position -= length;
      const buf = Buffer.alloc(length);
      await handle.read(buf, 0, length, position);
      const chunk = buf.toString('utf-8');
      text = chunk + text;
      for (let i = 0; i < chunk.length; i++) if (chunk.charCodeAt(i) === 10) newlines++;
    }
    // Drop a partial first line when we stopped mid-file (it may also split a UTF-8 sequence).
    if (position > 0) text = text.slice(text.indexOf('\n') + 1);
    return text;
  } finally {
    await handle.close();
  }
}

export async function readChatTranscript(agentId: string, opts: ReadTranscriptOptions = {}): Promise<ChatEvent[]> {
  await flushTranscript(agentId);
  const file = transcriptPath(agentId);
  let raw: string;
  try {
    // A plain tail (no session filter) only needs the end of the file.
    raw = opts.tail && !opts.sessionId ? await readTailText(file, opts.tail) : await fsp.readFile(file, 'utf-8');
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === 'ENOENT') return [];
    throw err;
  }
  const events: ChatEvent[] = [];
  for (const line of raw.split('\n')) {
    if (!line) continue;
    try {
      const parsed: unknown = JSON.parse(line);
      if (isChatEvent(parsed)) events.push(parsed);
    } catch {
      // A torn final line after a crash is skipped, not fatal.
    }
  }
  let filtered = opts.sessionId ? events.filter((e) => e.sessionId === opts.sessionId) : events;
  if (opts.sessionId && opts.afterSeq !== undefined) {
    const after = opts.afterSeq;
    filtered = filtered.filter((e) => e.seq > after);
  }
  return opts.tail ? filtered.slice(-opts.tail) : filtered;
}

/** Highest seq written for a session, so a resumed session continues the sequence. */
export async function lastSeqFor(agentId: string, sessionId: string): Promise<number> {
  const events = await readChatTranscript(agentId, { sessionId });
  return events.reduce((max, e) => Math.max(max, e.seq), 0);
}

export function transcriptExists(agentId: string): boolean {
  return fs.existsSync(transcriptPath(agentId));
}
